// プレイヤー(Pico)の版。
//
// 作曲ツールの版([tool/core/version.js](../core/version.js))とも、
// エンジンの版([sound/version.js](../../sound/version.js))とも別に動く。
// 置く側から見ると、この 3 つは別々に入れ替わる。
//
// 簡易鍵盤(keyboard.js)もこの数字で配る。リリースの zip
// (`mmsxx-player-<版>.zip`)が両方を入れているので、どちらを直しても上げる。
// 同じ名前で中身の違うものが出回ると、どちらを見ているのか分からなくなる
// (2026-10-24)
//
// 1.0.0 = 最初の版。鳴らす・跳ぶ・チャンネルを落とす・AB くり返し・
//         選んだところを MML で写す・WAV へ焼くまで。
//         `?` で版と権利を出す。
// 1.1.0 = チャンネルのボタンを Ctrl(Mac は Cmd)+クリックすると、
//         その行だけが残る。すでにその行だけなら全部戻る。

// 1.2.0 = チャンネルごとに WAV へ焼ける(↓ Stems)。押すと問いかけが開いて、
//         どのチャンネルを出すかと、曲ぜんぶに掛かる段(#fx)を掛けるかを選ぶ。
//         既定は掛けない。本格的なソフトで混ぜて仕上げるためのもので、
//         あちらで掛けるものを二重に掛けないため。
//         1 本しかない曲ではボタンを出さない。

// 1.3.0 = 簡易鍵盤(keyboard.js)が、計算機の鍵盤の 4 段ぜんぶを使う。
//         下の 2 段(zxcv と asdf)が下のオクターブ、上の 2 段(qwerty と数)が
//         その 1 つ上。DAW と同じ並びで、段の境目は 5 か所重なる。
//         出せるのが 18 半音(1 オクターブ半)から 29 半音(2 オクターブ半)になった。
//         鍵盤の本数の既定も 25 から 29 へ揃えた(広く打てて狭く出ていると、
//         押しても鳴らない字があることになる)。

// 1.4.0 = `saveMml: false` で、MML を落とす押しどころを作らない。
//         CSS で隠すのとは違って、節も聞くところも残らない。
//         `showMml` と `copy` は別の切り替えで、3 つ別々に消せる。

