// OPNA(YM2608)のリズム音源。6 つの打楽器の録音を、4 ビットの ADPCM-A で鳴らす。
//
// ---- 何を鳴らしているか ----
//
// 実機は ROM に入ったヤマハの録音を鳴らしている。それは配れないので、こちらで描き直した
// 6 音を入れてある(tool/opna-rhythm/)。録音の中身は違うが、鳴らし方は実機と同じ —
// 4 ビットの ADPCM-A を、BD・SD・TOP・HH は約 18.5kHz、TOM・RIM は約 9.2kHz で読む。
// 粗さはこの作りから出るので、似せた音でも OPNA らしく聞こえる(2026-10-05)。
//
// ---- 出どころ ----
//
// どのエミュレータも移していない。ADPCM-A の復号は公開されている仕組み
// (OKI の ADPCM と同じ表。刻みは 16 × 1.1^n の 49 段、上位 4 ビットが先)。
// 速さと長さは、実機の ROM の番地の表から出した値に合わせてある。
//
// ---- 決めたこと ----
//
// - OPLL のリズムと同じく、ふつうの音色として音符で鳴らす。o4c なら元の速さで、
//   ほかの高さを書けば比で速さを変える。実機は高さを変えられないので、ここは
//   実機に無い鳴らし方(書き出すときに見る)
// - 録音は終わりまで鳴る。音符の長さでは止めない(実機も止めずに鳴らしきる)
// - 同じ打楽器が重なったら、チップを足して両方鳴らす(数は縛らない)
// - 音量は打楽器ごとの 5 ビット(1 段 0.75dB)。全体の 6 ビットは最大のまま

