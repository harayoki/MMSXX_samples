/**
 * 6 音に共通の説明。録音は描き直したもので、ROM の中身ではない。
 * いずれ作り直して近づけるかもしれないので、音が変わることも書いておく
 */
const REDRAWN = ' Redrawn to sound like the YM2608 rhythm ROM, not the ROM data itself; '
  + 'played as 4-bit ADPCM-A at the chip\'s own rate. o4c plays it as recorded. '
  + 'The recording may be redrawn closer to the real chip later, so the sound can change.';

/**
 * 最初から入れておく音色を登録する(エンジンが読み込まれるときに走る)。
 * 二度呼ばれても止まらない(ほかの register* と同じ)。
 */
export function registerOPNARhythmPresets() {
  for (const [name, key, desc] of OPNA_RHYTHM_PRESETS) {
    try {
      registerOPNARhythm(name, { key },
        // OPNA を積んだ機械(PC-88FA / MA と PC-98 の 86 ボード)でだけ鳴る。
        // 描き直した録音なので、実機と同じとは言えない(approx。sound/mml.js の metaOf)
        { role: 'perc', desc: desc + REDRAWN, version: '1.00',
          tags: ['opna', 'pc88', 'pc98', 'drum', 'approx'] });
    }
    catch (e) { /* すでに入っている */ }
  }
}

