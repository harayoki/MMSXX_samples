// 0.54.0 = 途中へ跳んだときに、エフェクトの状態を数え直すようにした。
//          `seekBGM()` と A-B 再生の折り返しは「ここから先」だけを積むので、
//          跳んだ先より手前に書いた `@fx` と `@fxmaster` が飛んでいた。
//          飛ぶと、エフェクトが曲の頭の状態のままになる。手前の指示を名前ごとに
//          数え直して、最後の 1 つを書き込む(`_foldFx`)。外すぶんは余韻をかけずに
//          その場で外す。並びを上から押さえているあいだ(`overrideMasterChain`)は
//          曲ぜんぶのぶんを数え直さない
// 0.53.0 = JS の口も名前で指す形にした。`setMasterEffects` の各段に `name` を書ける
//          (書かなければ種類が名前。名前がぶつかると止める)。`tweakMasterEffects` と
//          `masterEffects()` `describeMasterEffects()` も名前で揃えた。
//          `tweakMasterEffects` は一時的なもので、曲(`@fxmaster`)が次にその値を
//          書いたところで曲に戻る(あとから書いたほうが勝つ)。積んであったぶんは
//          呼んだときに取り消すので、0.5 秒後に曲のぶんで上書きされることはない。
//          押さえたままにする `overrideMasterEffects(values, opts)` を足した。
//          `{名前: {パラメータ: null}}` で 1 つ手放し、`null` で全部手放す。
//          いま何を押さえているかは `masterOverrides()`。
//          並びを押さえる `overrideMasterChain(names)` も足した。押さえているあいだ、
//          曲の並びの書き替えは積まない。節を作り直したときは押さえを入れ直す
// 0.52.0 = 曲ぜんぶに掛けるエフェクトも、曲の途中で動かせるようにした。
//          `@fxmasterchain{<名前> …}` が並びを決めて、`@fxmaster{<名前> @mix 0.2}` が
//          1 つずつ動かす。書き方と積み方はチャンネルのぶんと同じ(`_scheduleFx`)。
//          どのチャンネルに書いてもよい。同じ時刻に別のチャンネルから違うことを書いたら
//          知らせて、前のチャンネル(番号の小さいほう)を通す。
//          名前なしの古い `#fx reverb 1.5` は消した。あれは曲ぜんぶの並びを指示行で
//          決める形で、途中では動かせなかった。`#fx <名前> = <種類>` の宣言だけが残る。
//          `#master`(仕上げの設定を名前で呼ぶもの)はそのまま
// 0.51.0 = 並びを曲の途中で切り替えられるようにした。`@fxchain{…}` は 1 チャンネルに
//          何度でも書ける。節は作り直さず、どれを通すかの出し入れで切り替える。
//          作り直すと前の並びのエコーとリバーブの残響が消えるため。
//          その代わり、2 つの並びで順番が食い違う書き方はできない
//          (`@fxchain{a b}` のあとに `@fxchain{b a}`)。通る位置は名前ごとに決まる。
//          エコーとリバーブを外すときは、`mix` を余韻の長さ(`fxTail`、上限 1.5 秒)を
//          かけて落とす。その場で 0 にすると、中で回っている残響が聞こえなくなって
//          切れたように聞こえる。曲の頭から通していないものは、頭で外しておく
// 0.50.0 = チャンネルのエフェクトを、番号から名前へ移した。
//          `#fx <名前> = <種類> [値]` で宣言して、並びは `@fxchain{<名前> …>}` が決める
//          (左から右へ通る)。1 つずつ動かすのは `@fx{<名前> @mix 0.2}` で、書いていない
//          パラメータはいまの値を保つ。名前だけ書くと宣言した値へ戻る。
//          外すのは `@fx{<名前> OFF}` と `@fxchain{OFF}`。
//          名前が種類そのものなら宣言は要らない(`@fxchain{lowpass echo}`)。
//          同じ種類を 2 つ並べるときだけ名前を付けて宣言する。
//          前は `@f{…}` `@f2{…}` `@f0` で、番号が順番を持っていた。1 つ挿すとうしろが
//          全部ずれるので、順番を並びの行へ移した。
//          指示行のうしろに注釈を書けるようにした(`#ch Lead // 主旋律`)。
//          落とすのは設定の行だけで、`#title` と `#about` は書いたものがそのまま値になる。
//          知らない指示行は読み飛ばして知らせる。前は `meta` へそのまま入れていたので、
//          `#tittle` のような打ち間違いがデータになっていた。
//          自由に書くものは `#meta <名前> <中身>`(`meta.extra` に入る)
// 0.49.0 = `defineBGM()` の入り口を 1 本のテキストにした。`// #ch` で切り分けるのを
//          エンジンの側でやる。前は配列も受けていて、切るのは呼ぶ側の仕事だった。
//          確かめる道(`validateMML`)だけが切っていたので、2 チャンネルと言われて
//          1 チャンネルで鳴る食い違いがあった。チャンネルごとに持っているものは
//          `joinVoices(parts, head)` でつないでから渡す(`splitVoices()` の逆)。
//          2 つめの引数は曲ぜんぶに効く指示行で、最初の `#ch` より前に置かれる
// 0.48.0 = ラベルがチャンネルをまたいで食い違っていたら知らせるようにした。
//          鳴らす側は、その名前を持っている最初のチャンネルを採る。ほかのチャンネルに
//          違う時刻で書いてあっても黙って捨てていた。同じ時刻にそろっているぶんには
//          言わない(読みやすさのために全部のチャンネルの同じところへ書くのはありえる)。
//          `OUTRO` は曲の 1 周の終わりを決めるのでエラー、それ以外は警告。
//          `LOOP` は前から見ていた
// 0.47.0 = 全体のエフェクト(`setMasterEffects` `#fx` `#master`)を掛け直したときに、
//          継ぎ目で音が切れていたのを直した。並びを丸ごと作り直していたので、作りたての節は
//          中身が空から始まり、遅れ線を持つもの(`tape` の揺れは 10ms)はそのあいだ 0 を出していた。
//          同じ設定へ掛け直しても 10〜18ms 消えていた。いまは新しい並びを先につないで 20ms
//          黙らせたまま流し込み、埋まってから 5ms で混ぜ替える。前の並びは混ぜ終わってから外す。
//          エコーとリバーブの響きは作り直すぶん消える(残したいときは `tweakMasterEffects()` で
//          値だけを動かす)
// 0.46.0 = フィルタ 6 つに `mix`(通した音と元の音の混ぜ具合、0〜1、既定 1)を入れた。
//          途中で動かせる。`@f0` はフィルタでは `mix` を 0 にする。前はカットオフを端へ寄せていて、
//          bandpass・notch・highpass4 は外しても素通しにならず、highpass4 は音がほとんど消えた。
//          tube・transformer・tape など、動かせる値を持たない段が `@f0` で外れなかったのを直した。
//          エフェクトを 3 つ加えた(作業中)。`noisefill` は音の形に沿ったノイズを足す。
//          `denoise` は帯ごとにノイズを絞る(遅れなし)。`spectralgate` は細かいスペクトルで
//          山を残し、鳴っている音の下のノイズも取る(21ms 遅れる)。
//          `tape` の幅を広げた。`drive` の上限 18dB → 30dB、`speed` の下限 7.5 → 3.75ips、
//          `wow` の揺れ 1% → 3%、`flutter` 0.3% → 1%。既定の音は変えないよう、既定の値を
//          下げた(`drive` 0.18、`wow` 0.017、`flutter` 0.03)。同じ値を書いた曲は強く掛かる。
//          `tape` の遅れは 4ms → 10ms(`TAPE_LATENCY`)
// 0.45.0 = `renderBGM` に `masterFx` を入れた。`false` にすると、曲ぜんぶに掛かる段
//          (`#fx` `#master` `setMasterEffects`)を外して焼く。チャンネルの `@f` と
//          音色の中のものは外さない(あれはチャンネルの持ち物で、1 本だけ焼いても付いてくる)。
//          `mute` と組み合わせると、チャンネルごとに 1 本ずつ焼ける。別々に出したものを
//          本格的なソフトで混ぜて仕上げるときに要る。あちらで掛けるものを二重にしないため。
//          外して焼けば、足し合わせたものが曲に戻る(16 ビットの丸めぶんしかずれない)。
//          掛けたまま焼くと、音の大きさで効き方が変わる段(`limiter` `saturate`
//          `compressor` など)では戻らない。1 本ずつは小さいので、ほとんど効かない
// 0.44.0 = エフェクトの値を、鳴らしている途中で動かせるようにした。
//          `@f` はどの値でも書き替えられる。1 つの節のまま動くのは、フィルタのカットオフ・
//          レゾナンス・飽和、echo の `time` `feedback` `mix` `tone`、reverb の `mix`。
//          それ以外(echo の `cross`、reverb の `time` `width`)は、組み合わせごとに並びを
//          1 本ずつ作って出口の音量で入れ替える。同じ組み合わせは使い回すので、
//          行ったり来たりしても増えない。どの並びにも音を入れ続けるので、入れ替えても
//          溜まっていた返りや響きは消えない。前は「作るときに値が決まる」として断っていた。
//          `@f0` と `@f2{off}` でエコーとリバーブも切れる(素通しの脇道へ移す)。
//          書き直せば戻る。前はフィルタしか外れなかった。
//          全体のエフェクトには `tweakMasterEffects(values, opts)` を足した。並びを作り直さずに
//          値だけを動かすので、響きが切れない(`setMasterEffects` は作り直す)。`fade` で寄せられる。
//          パラメータに `live` の札を付けた。途中で動かせるかが `describeMasterEffects()` で分かる。
//          1 台にできる並びが 4 本を越えたら知らせ、16 本を越えたら止める。
//          分かって越えるなら `compileMML(src, { allowOverLimit: true })`(`defineBGM` にも渡せる)。
//          アナログ音源に 2 台目のフィルタ(`filter2.kind` `filter2.cutoff` `filter2.resonance`)を足した。
//          1 台目のうしろに置いて動かさない。帯の反対側を削るのに使う(書かなければ 2 台目は無い)。
//          音色の札に `byEar` を足した。実機の録音と聞き比べて耳で合わせた音に付ける
// 0.43.0 = アナログ音源の音量のエンベロープに、かけ直す回数と間隔(`amp.repeat` `amp.gap`)と、
//          ゆっくり減る尾(`amp.tail` `amp.tailDecay`)を入れた。手拍子のように、同じ山を
//          少しずつずらして何回か重ねる音のため。流れ続けるノイズに音量だけをかけ直すので、
//          山ごとに中身が違う(ディレイで写すと、同じ波形のくり返しが音の高さになる)。
//          既定のままなら前と同じ計算になる。音量がフィルタより前にある音色だけ。
//          保つあいだもゆっくり減らせる `amp.holdDecay` も入れた(秒。60dB 減るまでの長さ)。
//          鳴りながら少しずつ減ってから切れる音のため。0 なら前と同じで、保つあいだは平ら
// 0.42.0 = `*`(ポルタメント)を、2 つの音符をつなぐ形に直した。どちらも書いた長さのまま鳴り、
//          境目をまたいで滑る。鳴り直さない。前は「音符 1 つの中で滑る」で、`*` のあとの長さが
//          前の音符の長さを置き換えていた。**前の曲は長さが変わる** — `c*g` は 2 音ぶんになり、
//          `c*g2` は「2 つめが 2 分音符」の意味になる。
//          滑る範囲を `*{前,後}` で書ける(`l1 a*{8,8}d`)。数が 1 つなら境目で半分ずつ、0 も書ける。
//          音符より長ければ縮めて知らせる。滑っているあいだは `q` の隙間を埋めるので、
//          `q` を縮めても滑る速さは変わらない(前は変わっていた)。
//          合成音色(`registerLayer`)に、デチューン幅を呼ぶときに渡せる軸を入れた
//          (`@{名前(detune: 25)}`。セント)。いちばん広くずらしている層がその幅になり、
//          ほかの層は同じ比で伸び縮みする。軸の既定はその音色が持っている幅。
//          `stopSE(id, { fade })` を入れた。鳴っている途中で切るとプツッと鳴るので、
//          少し落としてから止める(既定 0 で、今までの呼び方は変わらない)
// 0.41.0 = 音をまたいで高さと揺れを動かす `@pitch{+700,2}` `@vibrato{40,2}` を入れた。`@fade` と同じ形で、
//          書いたところから拍数かけて行き先まで動き、次に書くまでとどまる。音符の区切りを見ない。
//          高さは上下 1 オクターブ(セント)、揺れは深さ(セント)と、書けば速さ。analog の音色だけ
// 0.40.0 = 冨田勲風の鐘 `analog::tomitaBell`(作業中)を加えた。Moog System 55 の動画の録音から測った
//          倍音の比(1 : 1.035 : 1.618 : 2.437 : 3.233)のサイン波を並べて足す。
//          analog の発振器に、サイン波を並べて足す `partials` を入れた(`osc.partials` に 8 本まで、
//          1 本ずつ何倍の高さか・大きさ・立ち上がり・減り方)。2 つの音を掛ける(リング)だけでは比が揃わないため
// 0.39.0 = 揺れの並び(`@vib{0 30 0 50:8}`)を入れた。音符が 1 つ鳴るたびに次の値へ進み、
//          その音のビブラートの深さ(セント)と、書けば速さ(Hz)を決める。揺れは音の頭から。
//          書いているあいだは `@m` と音色のビブラートより勝つ。進み方は `@steps` と同じ。パピプペ親父の専用の記法の 3 回目
// 0.38.0 = 再生の定位の既定を `mono` にし、`auto` を消した。ステレオは `spatial: 'stereo'` と頼んだときだけ。
//          `mono` では出口で 1 本に畳むので、リバーブやコーラスが左右で別の音を出しても広がらない。
//          そのうえで、リバーブの `width` と analog の `reverb.width` `chorus.width` の既定を 1 に戻した。
//          ステレオで出すかは再生する側が決めることで、響きごとに決めることではないため
// 0.37.0 = 高さの並び(`@bend{+80 -50 0}`)を入れた。値はセントで、音符が 1 つ鳴るたびに次へ進む。
//          音はその分ずれた高さから始まり、音の長さをかけて書いた高さへ戻る。analog の音色だけ。
//          進み方は `@steps` と同じ。パピプペ親父の専用の記法の 2 回目。
//          analog のコーラスに `chorus.width` を入れた。既定は 0 で、揺れは中央に収まる
//          (前は左右で逆に揺れ、voxHumana などが左右を行き来していた)。リバーブの width と揃えた
// 0.36.0 = tomitaStrings の軽い版 `analog::tomitaStringsAlt` を加えた。既定は矩形波・3 本・
//          リバーブなしで、波形を呼ぶときに選べる(`wave: saw / square / sine / triangle /
//          pulse25 / pulse12 / pwm / octaveSaw / pulse33 / sync / halfSine`)。0.33.0 の `squareEnsemble` はこれの矩形波にまとめて消した。
//          analog の発振器にサイン波・三角波・オクターブ重ねのこぎり波・半分のサイン波を入れ、
//          パルスの幅を `osc.width` で決められるようにした
//          (書かなければ前と同じ 25%)。リバーブを既定で使うかを音色ごとに決める `reverb.on` を入れた。
//          PWM を 1 本だけ鳴らす `analog::pwm` を加えた(フィルタは開けたまま、コーラスもリバーブも無し)
// 0.35.0 = 開く量の並び(`@steps{9 3 6}`)を入れた。音符が 1 つ鳴るたびに次の値へ進み、
//          analog の音色ではフィルタの開く量を決める(強さの代わり)。0〜9。
//          休符とスラーの続きでは進まず、和音は声ごとに進む。`@steps0` で止める。
//          パピプペ親父の専用の記法の 1 回目。高さの動きはまだ無い
// 0.34.1 = 0.34.0 の `wavePulse33` を `wavePulse( )` の作り分けに入れて `wavePulse(33)` にした。
//          32 点では 1/3 にならない(11/32 で 34.4%)ので、これだけ 96 点の表で 33.3% ちょうど
// 0.34.0 = 基本の音色に 4 つの形を加えた。波形メモリ版(`waveHalfSine` `waveSync` `waveOctaveSaw`
//          `wavePulse33`、32 点・8 ビット)と、きれいな版(`halfSine` `syncSaw` `octaveSaw` `pulse(33)`)。
//          `registerWave` に鳴らす高さのずれ `octave` を入れた(octaveSaw は -1)
// 0.33.0 = analog の発振器にユニゾンを入れた(`osc.unison` `osc.spread`)。1 つの声の中で
//          のこぎり波か矩形波を何本も重ねる。ずらし方は不ぞろい、真ん中ほど大きく、
//          位相は声ごとにばらばらから始める(同じ位相から始めると、毎回同じ形でうねる)。
//          analog のサブチャンネルに小さなリバーブを入れた(`reverb.mix` `reverb.time`)。
//          それを使って、冨田勲風のストリングス `analog::tomitaStrings` と、
//          矩形波版 `analog::squareEnsemble` を加えた。
//          analog を呼ぶときに `voices`(重ねる本数 1〜20)と `reverb`(on / off)を渡せる。
//          数を受け取る軸が 2 本になったので、`analog::x(100)` のような数だけの書き方は
//          どの軸か分からず止まる。`vibrato: 100` と名前を付けて書く
// 0.32.0 = ビブラート(`@m`)の深さをセントにし、速さを深さから切り離した。
//          前は深さが 0〜9 の目盛り(1 で約 6.9 セント)で、速さを書かないと
//          5 + 深さ × 0.6 Hz になっていた。本物のビブラートは深くしても速くならない。
//          いまは `@m40` で上下に 40 セント、速さは書かなければ 5.5Hz。0〜100。
//          音色の `vib` の深さも同じセントにした。
//          **前の曲は書き直しが要る。**同じ鳴り方にする置き換え:
//          `@m1`→`@m{7,5.6}` `@m2`→`@m{14,6.2}` `@m3`→`@m{21,6.8}` `@m4`→`@m{28,7.4}` `@m5`→`@m{35,8}` `@m6`→`@m{41,8.6}` `@m7`→`@m{48,9.2}` `@m8`→`@m{55,9.8}` `@m9`→`@m{62,10.4}`。
//          `@m{5,7}` のように速さを書いていたものは、深さだけ直す(`@m{35,7}`)。
//          遅れ(3 つ目)はフレームのままで変わらない。
//          あわせて、analog の音色でも `c*g`(ポルタメント)と `@m` が効くようにした。
//          前は黙って無視していた。
//          音色を呼ぶときに数を渡せるようにした(`@{analog::tomitaWhistle(vibrato: 100)}`)。
