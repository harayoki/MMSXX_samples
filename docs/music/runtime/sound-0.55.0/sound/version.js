// 0.55.0 = 曲ぜんぶのものを 2 回書いたら通さないようにした。`LOOP` と `OUTRO` は
//          エラー、ほかのラベルは警告、`@fxmaster` の同じ時刻の重なりも警告。
//          同じ時刻にそろえてあっても通さない。前は食い違ったときだけ止めていたので、
//          どちらが通るのか読めないまま鳴ることがあった。鳴らす側は、その札を持って
//          いる最初のチャンネルを採る。見通しのために各チャンネルへ書きたいときは
