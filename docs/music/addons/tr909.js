/** 種から 0〜1 を出す(xorshift)。雲の並びを毎回同じにする */
function ohRandom(seed) {
  let s = (seed * 2654435761 >>> 0) || 1;
  return () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
}
/**
 * 山のあいだを埋める雲。[Hz, 大きさ, DECAY 10 での 60dB の秒] を、並べ方 `cymbal` と同じ散らし方で並べる
 * (上ほど詰める。pow を 1 にすると、高さの対数で一様に散らす)。向きは種で決める。叩くのがクリックなので、向きを揃えると叩いた瞬間に重なって尖る
 */
function ohCloud({ count, lo, hi, t, seed, level, pow = 0.6 }) {
  const r = ohRandom(seed), out = [];
  for (let n = 0; n < count; n++) {
    const ratio = Math.exp(Math.log(lo) + (Math.log(hi) - Math.log(lo)) * Math.pow(r(), pow));
    out.push([ratio * OH_MEASURED, (r() < 0.5 ? -1 : 1) * level * (0.3 + 0.7 * r()), t * (0.5 + r())]);
  }
  return out;
}
