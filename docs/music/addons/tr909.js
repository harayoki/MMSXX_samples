  const xr = lerp(TOM_AT, t.x, tune), xg = Math.pow(10, lerp(TOM_AT, t.xdb, tune) / 20);
  const third = TOM_HARM.filter(([, a]) => a * xg >= TOM_FLOOR).map(([n, a]) => ({ ratio: up * xr * n, level: a * xg, attack: 0.0005, t60: TOM_X_T60 }));
  p.osc.partials = [...one(up, 1), ...one(up / t.ratio, low), ...third];
  Object.assign(p.amp, { attack: 0.004, hold: 4, holdDecay: t60, decay: 0.01, sustain: 0, release: t60 / 2.303 });
  Object.assign(p.pitch, { drop: 12 * Math.log2(lerp(TOM_AT, TOM_DROP, tune)), dropHold: TOM_DROP_HOLD, dropTime: TOM_DROP_TIME });
  p.tom = { tune, decay };
