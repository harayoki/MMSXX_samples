/** 目盛りの表を、間の値はまっすぐつないで引く */
function lerp(xs, ys, v) {
  if (v <= xs[0]) return ys[0];
  for (let i = 1; i < xs.length; i++) {
    if (v <= xs[i]) {
      const t = (v - xs[i - 1]) / (xs[i] - xs[i - 1]);
      return Array.isArray(ys[0]) ? ys[i - 1].map((a, k) => a + (ys[i][k] - a) * t) : ys[i - 1] + (ys[i] - ys[i - 1]) * t;
    }
  }
  return ys[ys.length - 1];
}

