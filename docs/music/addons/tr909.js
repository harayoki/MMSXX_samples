/**
 * Drum machine voices in the manner of the TR-909.
 * Addon: tr909 (v1.0.0)
 * Needs the subtractive synth (analog) and the resonator source (acoustic).
 *
 * All eleven instruments of the original: the bass drum, the snare drum, the low, mid and high
 * toms, the rim shot, the hand clap, the closed and open hi-hats, the crash cymbal and the ride
 * cymbal.
 *
 * The bass drum, the snare drum, the toms and the hand clap are built on the subtractive synth,
 * as the original builds them from analog circuits. The bass drum is a sine that starts high and
 * drops to the written note right after it is struck, with a short click of noise on top. The
 * snare drum is two tones for the shell that start high and fall, under a hiss of noise for the
 * wires. Each tom is two tones close to triangles, a fixed interval apart, that drop to the note
 * in the same way, with a third tone that dies away quickly and a short burst of noise. The hand
 * clap is noise struck four times, a little unevenly, with a darker tail like the ring of a small
 * room.
 *
 * The rim shot and the voices the original plays from recordings are built on the resonator
 * source. The rim shot is three ringing tones struck at once, clipped together and cut short,
 * with a tiny tick of noise on the front. The hi-hats, the crash and the ride are the strongest
 * peaks of a recording laid out as resonators at their measured pitches, levels and lengths, with
 * a cloud filling in between, struck by a short click and softly squashed. The tune of the crash
 * and the ride plays the whole table higher and shorter together, as the original plays its
 * recording faster. A closed hi-hat stops an open one that is ringing on the same channel.
 *
 * The knobs of the original are knobs passed when the voice is called, 0 to 1 for 0 to 10 on the
 * machine; the level is v. The pitch drops, the lengths, the bands and the knob curves were
 * matched to recordings of a real machine (Rob Roy Recordings, 1995); the way each voice is built
 * is still a guess.
 */
